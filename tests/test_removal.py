def rules(goal):
    """The rules of a goal's KBSECTION, each as (head, conditions, actions)."""
    kb = goal.split("KBSECTION", 1)[1].split("EXITSECTION", 1)[0]
    kb = re.sub(r"//[^\n]*", "", kb)
    out = []
    for m in re.finditer(r"\b(IF|PROC|QRY)\n(.*?)\nTHEN\n(.*?)(?=\n\s*\n|\Z)", kb, re.S):
        conditions = [c.strip() for c in m.group(2).split("\nAND\n")]
        actions = [a.strip() for a in m.group(3).strip().split("\n") if a.strip()]
        out.append((m.group(1), conditions, actions))
    return out


class Uninstaller(unittest.TestCase):
    def setUp(self):
        self.waypoints = load(DATA_FILE)["waypoints"]
        self.goal = build_waypoints.uninstaller_goal(self.waypoints)
        self.mod_goal = build_waypoints.goal(self.waypoints)

    def test_every_waypoint_is_listed(self):
        for wp in self.waypoints:
            self.assertIn('DB_NEW_WAYP_Uninstall("%s");' % wp["id"], self.goal)

    def test_it_names_no_object(self):
        # It finds the shrine and the arrival point through the story, never by GUID: once the mod
        # is gone, its objects are too, and the uninstaller must not depend on them.
        for wp in self.waypoints:
            for part in ("shrine", "trigger", "decal", "rock"):
                if part in wp:
                    self.assertNotIn(wp[part]["guid"], self.goal, wp["id"])

    def test_starts_with_the_story_and_keeps_the_mods_list(self):
        self.assertNotIn("ParentTargetEdge", self.goal)
        init = self.goal.split("KBSECTION")[0]
        self.assertIn('NOT DB_NEW_WAYP_Waypoint("");', init)   # declared, so its facts survive the mod

    def test_it_stands_down_while_the_mod_is_loaded(self):
        events = [r for r in rules(self.goal) if r[0] == "IF"]
        self.assertEqual({r[1][0] for r in events}, {"SavegameLoaded()", "LevelGameplayStarted(_, _)"})
        for _head, conditions, actions in events:
            self.assertIn('NOT SysIsActive("%s")' % MOD, conditions)
            self.assertEqual(actions, ["PROC_NEW_WAYP_Uninstall();"])

    def test_locks_before_forgetting(self):
        # The game's lock needs DB_WaypointInfo and DB_WaypointUnlocked: both go after it, in one rule.
        main = [r for r in rules(self.goal) if r[1][0] == "PROC_NEW_WAYP_Remove((STRING)_ID)"
                and any(c.startswith("DB_WaypointInfo(") for c in r[1])]
        self.assertEqual(len(main), 1)
        actions = main[0][2]
        self.assertEqual(actions[0], "PROC_LockWaypointForAll(_ID);")
        self.assertLess(actions.index("PROC_NEW_WAYP_ForgetUnlocks(_ID);"),
                        actions.index("NOT DB_WaypointInfo(_Group, _ID, _Shrine, _Trigger);"))

    def test_takes_out_what_the_mod_puts_in(self):
        # Every database of the game that the mod writes to, and those the game fills for a waypoint
        # once it is unlocked or travelled to, is cleared. A new write in the mod's story fails here
        # until the uninstaller clears it too.
        init = self.mod_goal.split("KBSECTION")[0]
        written = set(re.findall(r"^(DB_\w+)\(", init, re.M)) | {"DB_WaypointUnlocked", "DB_QRYRTN_Waypoints_IDFromString"}
        for db in sorted(written - {"DB_NEW_WAYP_Waypoint"}):
            self.assertRegex(self.goal, r"\nNOT %s\(" % re.escape(db), db)
        self.assertIn("NOT DB_NEW_WAYP_Waypoint(_ID);", self.goal)

    def test_generated_file_is_current(self):
        with open(build_waypoints.UNINSTALLER_GOAL, encoding="utf-8", newline="") as fh:
            self.assertEqual(fh.read().replace("\r\n", "\n"), self.goal)


class Meta(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.mkdtemp()
        self.saved = build_waypoints.UNINSTALLER_META

    def tearDown(self):
        build_waypoints.UNINSTALLER_META = self.saved
        shutil.rmtree(self.tmp)

    def uninstaller_meta(self, change):
        with open(self.saved, encoding="utf-8") as fh:
            text = change(fh.read())
        path = os.path.join(self.tmp, "meta.lsx")
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(text)
        build_waypoints.UNINSTALLER_META = path

    def test_both_are_fine(self):
        errors = []
        build_waypoints.check_meta(errors)
        self.assertEqual(errors, [])

    def test_versions_must_match(self):
        self.uninstaller_meta(lambda t: t.replace("36310271995674624", "36028797018963968"))
        errors = []
        build_waypoints.check_meta(errors)
        self.assertTrue(any("released together" in e for e in errors), errors)

    def test_uuid_and_folder(self):
        with open(build_waypoints.META, encoding="utf-8") as fh:
            mod_uuid = re.search(r'id="UUID" type="FixedString" value="([^"]+)"', fh.read()).group(1)
        self.uninstaller_meta(lambda t: re.sub(r'(id="UUID" type="FixedString" value=")[^"]+', r"\g<1>" + mod_uuid, t)
                              .replace('value="%s"' % UNINSTALLER, 'value="%s"' % MOD))
        errors = []
        build_waypoints.check_meta(errors)
        self.assertTrue(any("mod's UUID" in e for e in errors), errors)
        self.assertTrue(any("Folder is" in e for e in errors), errors)


