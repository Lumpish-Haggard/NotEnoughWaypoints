class StoryCheck(unittest.TestCase):
    def test_debug_log(self):
        aliases, enums, functions = check_story.read_debug_log(DEBUG_LOG.splitlines(True))
        self.assertEqual(enums, {"DEATHTYPE": {"CHASM": 2, "NONE": 0}})
        self.assertEqual(aliases[21], ("ITEMROOT", 19))
        self.assertEqual([f[1] for f in functions], ["LockWaypoint", "GetHostCharacter", "LevelGameplayStarted", "SysIsActive"])
        header = check_story.story_header(aliases, functions).splitlines()
        self.assertIn("alias_type {ITEMROOT,21,5}", header)   # down to the intrinsic type, as LSLib wants
        self.assertIn("alias_type {DEATHTYPE,26,2}", header)
        self.assertIn("call LockWaypoint((STRING)_P1,(CHARACTER)_P2) (1,0,661,1)", header)
        self.assertIn("query GetHostCharacter([out](CHARACTER)_P1) (2,0,113,1)", header)
        self.assertIn("event LevelGameplayStarted((STRING)_P1,(INTEGER)_P2) (3,0,1053,1)", header)
        self.assertIn("sysquery SysIsActive([in](STRING)_P1) (102,0,0,0)", header)
        self.assertFalse([h for h in header if "PROC_" in h or "DB_" in h])   # those are the goals' own

    def test_enums_become_numbers(self):
        text, unknown = check_story.rewrite_enums("Die(_P,DEATHTYPE.Chasm,_C,1,1);\nX(DEATHTYPE.Lava);",
                                                  {"DEATHTYPE": {"CHASM": 2}})
        self.assertEqual(text, "Die(_P,2,_C,1,1);\nX(DEATHTYPE.Lava);")
        self.assertEqual(unknown, 1)

    def test_messages_and_what_is_new(self):
        baseline = check_story.messages(
            "ERR! Mods\\Shared\\Story\\RawFiles\\Goals\\A.txt:3:1: ERR! Mods\\Shared\\Story\\RawFiles\\Goals\\B.txt:9:4: "
            "[X00] Could not parse goal file A\n[X00] Could not parse goal file B\n"
            'ERR! [E25] Database "DB_Old(1)" is read, but is never written to\n')
        self.assertEqual([m[:2] for m in baseline], [("X00", "Could not parse goal file A"),
                                                     ("X00", "Could not parse goal file B"),
                                                     ("E25", 'Database "DB_Old(1)" is read, but is never written to')])
        run = baseline + check_story.messages(
            'ERR! [E25] Database "DB_Typo(1)" is read, but is never written to\n'
            "ERR! Mods\\%s\\Story\\RawFiles\\Goals\\%s.txt:12:3: [E11] Parameter _P1 of SysQuery \"SysIsActive\" "
            "expects STRING; INTEGER specified\n" % (UNINSTALLER, UNINSTALLER))
        new = check_story.added(baseline, run)
        self.assertEqual(len(new), 2)
        self.assertEqual(new[1][2], "Mods/%s/Story/RawFiles/Goals/%s.txt" % (UNINSTALLER, UNINSTALLER))
        self.assertEqual(new[1][3], 12)
        # a message about one of our goals counts even when the game's story gives the same text
        ours = ("E21", "same text", "Mods/%s/Story/RawFiles/Goals/%s.txt" % (MOD, MOD), 4)
        self.assertEqual(check_story.added([("E21", "same text", None, None)], [ours]), [ours])


