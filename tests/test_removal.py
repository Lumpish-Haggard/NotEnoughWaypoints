class SaveInspector(unittest.TestCase):
    def setUp(self):
        self.marks = inspect_save.our_marks(load(DATA_FILE)["waypoints"])

    def test_story(self):
        goals, facts = inspect_save.read_story_log(STORY_LOG.splitlines(True), self.marks)
        self.assertEqual(goals, {MOD: "running", UNINSTALLER: "completed"})
        self.assertEqual(sorted(facts), ["DB_QRYRTN_Waypoints_IDFromString", "DB_WaypointUnlocked"])
        self.assertEqual(len(facts["DB_WaypointUnlocked"]), 1)   # the game's own waypoint is not ours

    def test_globals(self):
        blob = base64.b64encode(b"LSMF\x01junkWAYP_DEN_CampNEW_WAYP_DEN_HollowWAYP_FOR_RuinsNEW_WAYP_ZZZ_Later\x00").decode()
        text = ('<region id="RegisteredWaypoints"><node id="RegisteredWaypoints"><children>'
                '<node id="RegisteredWaypoint"><attribute id="WaypointName" type="FixedString" value="WAYP_DEN_Camp" />'
                '</node><node id="RegisteredWaypoint">'
                '<attribute id="WaypointName" type="FixedString" value="NEW_WAYP_GOB_Sanctum" /></node>'
                '</children></node></region>'
                '<node id="Creator"><attribute id="TemplateID" type="FixedString" '
                'value="4a56b43b-456d-4556-8d14-d7f62c62b4e3" /></node>'
                '<region id="NewAge"><node id="NewAge"><attribute id="NewAge" type="ScratchBuffer" value="%s" />'
                '</node></region>' % blob)
        registered, objects, party = inspect_save.read_globals(text, self.marks)
        self.assertEqual(registered, ["NEW_WAYP_GOB_Sanctum"])
        self.assertEqual(objects, ["NEW_WAYP_DEN_Hollow arrival point"])
        self.assertEqual(party, ["NEW_WAYP_DEN_Hollow", "NEW_WAYP_ZZZ_Later (not in waypoints.json)"])

    def test_mods(self):
        text = ('<node id="ModuleShortDesc"><attribute id="UUID" type="guid" value="x" />'
                '<attribute id="Version64" type="int64" value="36169534507319296" />'
                '<attribute id="Folder" type="LSString" value="NotEnoughWaypoints" />'
                '<attribute id="Name" type="LSString" value="Not Enough Waypoints" /></node>')
        self.assertEqual(inspect_save.read_mods(text), [("Not Enough Waypoints", "NotEnoughWaypoints", "1.1.0.0")])

    def test_verdict(self):
        self.assertEqual(inspect_save.verdict({MOD: "running"}, {}, [], [], [])[0], 1)
        self.assertEqual(inspect_save.verdict({}, {"DB_WaypointInfo": ["x"]}, [], [], [])[0], 1)
        self.assertEqual(inspect_save.verdict({}, {}, [], [], ["NEW_WAYP_DEN_Hollow"])[0], 1)
        status, sentence = inspect_save.verdict({UNINSTALLER: "running"}, {}, ["NEW_WAYP_DEN_Hollow"], [], [])
        self.assertEqual(status, 0)
        self.assertIn("uninstaller is still loaded", sentence)
        self.assertEqual(inspect_save.verdict({}, {}, [], [], []), (0, "Nothing of Not Enough Waypoints is left in this save."))


